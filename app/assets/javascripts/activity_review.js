$(document).ready(function() {
  $("#recorded_comments_arc_player").initialize_inactive_player();
  $('img.recording_decor').bind('click', function() {
    VHL.ActivityReview.play_recorded_comment(this);
  });
  VHL.AddNoVisualForA11Y();
});

VHL.ActivityReview = (function(){
  
  var play_recorded_comment = function(recorded_comment_button)
  {
    $('#recorded_comments_arc_player').dialog({
        title: 'Instructor comment',
        minHeight: 150,
        minWidth: 300,
        modal: false,
        position: 'center',
        resizable: false,
        width: 200,
        closeOnEscape: false,
        beforeClose: function(event, ui){
          stop_players_if_playing_or_recording();
          detach_player_instance_from_arc_container(recorded_comment_button);
        },
        open: function(event, ui) { 
          initialize_comment_player(recorded_comment_button);
          $("#recorded_comments_arc_player .play").click();
        }
    });
    return false;
  };
  
  var detach_player_instance_from_arc_container = function(recorded_comment_button)
  {
    var server_host = $('#recording_server_url').val();
    var recording_path = $(recorded_comment_button).attr('data-recording-path');
    var params = {server_host: server_host, 
                  recording_path: recording_path};
    var player = VHL.Recording.retrieve_arc_player_if_exists(params);
    if(player)
    {
      $.removeData($("#recorded_comments_arc_player"), player);                  
    }
  };
  
  var stop_players_if_playing_or_recording = function()
  {
    if(ARC)
    {
      var player_instances = ARC.Manager.players;
      var player;
      for(var index in player_instances)
      {
        player = player_instances[index];
        if(player.state() == 'playing' || player.state() == 'recording')
        {
          player.stop();
        }
      }
    }
  };
  
  var initialize_comment_player = function(recorded_comment_button)
  {
    var server_host = $('#recording_server_url').val();
    var load_balancer_url = $('#load_balancer_url').val();
    var recording_path = $(recorded_comment_button).attr('data-recording-path');
    var params = {server_host: server_host, 
                  recording_path: recording_path,
                  load_balancer_url: load_balancer_url};
    $("#recorded_comments_arc_player").ckeditor_comment_player(params);
  };
  
  return{
    play_recorded_comment: play_recorded_comment
  };
})();

VHL.AddNoVisualForA11Y = function(){
  /**
  * Making Instrcutor Feedback accessible by appending hidden "#{Feedback} start" and "#{feedback} end" span elements to the instructor feedback
  * The feedback is being generated by CKEditor when instructor is grading the activity.
  * Accessiblity for Feedback is being added after the DOM has been loaded (via JS) instead of doing so on sever side (erb)
  * This is because to achieve this on the server side will need heavy string manipulation on the HTML read as string from the datastore
  */
  $(".ns-open-ended .instructor_deletion").prepend("<span class='u-no-visual'> deletion start </span>").append("<span class='u-no-visual'> deletion end </span>");
  $(".ns-open-ended .instructor_addition").prepend("<span class='u-no-visual'> addition start </span>").append("<span class='u-no-visual'> addition end </span>");
  $(".ns-open-ended .instructor_comment").prepend("<span class='u-no-visual'> comment start </span>").append("<span class='u-no-visual'> comment end </span>");
}
